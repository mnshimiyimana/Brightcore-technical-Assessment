CREATE TABLE admin_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE jobs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(150) NOT NULL,
    location         VARCHAR(120) NOT NULL,
    employment_type  VARCHAR(20)  NOT NULL,
    summary          VARCHAR(300) NOT NULL,
    description      TEXT         NOT NULL,
    responsibilities TEXT         NOT NULL,
    requirements     TEXT         NOT NULL,
    closing_date     DATE         NOT NULL,
    status           VARCHAR(10)  NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_jobs_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT chk_jobs_type CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERNSHIP'))
);

-- The public jobs page filters on status + closing date.
CREATE INDEX idx_jobs_status_closing ON jobs (status, closing_date);

CREATE TABLE applications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id           BIGINT       NOT NULL REFERENCES jobs (id),
    full_name        VARCHAR(120) NOT NULL,
    email            VARCHAR(255) NOT NULL,
    phone            VARCHAR(20)  NOT NULL,
    cover_note       TEXT         NOT NULL,
    cv_storage_key   VARCHAR(64)  NOT NULL,
    cv_original_name VARCHAR(255) NOT NULL,
    cv_size_bytes    BIGINT       NOT NULL,
    status           VARCHAR(10)  NOT NULL,
    decision_note    VARCHAR(1000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_applications_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    -- Last line of defence against the same person applying twice (emails are stored lower-cased).
    CONSTRAINT uq_applications_job_email UNIQUE (job_id, email)
);

CREATE INDEX idx_applications_job_status ON applications (job_id, status);
